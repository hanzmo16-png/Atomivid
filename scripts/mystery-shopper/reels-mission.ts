/** Real UI runner. No API mutation, direct provider call, automatic retry, or fake media acceptance. */
import path from "node:path";
import { writeFile } from "node:fs/promises";
import type { RealCtx } from "./real-missions";
import { campaign320SpendGate } from "../../src/lib/mystery-shopper/v3/campaign-320-adapters";
import { measureVideo } from "./av-check";

export async function runReelReal(c: RealCtx): Promise<void> {
  const p = c.page, title = `QA Reel ${c.jobId}: cómo se forman las nubes`;
  let id = "", reserved = false;
  const key = `${c.jobId}-reels`;
  const sleep = c.sleep ?? ((ms: number) => p.waitForTimeout(ms));
  const opened = await c.step("Abrir y configurar Reel de 30 segundos", async () => {
    const m = await c.goto("/dashboard/new?formato=reel");
    if (m.httpStatus !== 200 || new URL(p.url()).pathname === "/login") return { state: "BLOCKED", detail: "No se pudo abrir el formulario Reel autenticado." };
    await p.getByLabel("Tema o instrucciones", { exact: true }).fill(title);
    await p.getByLabel("Idioma de la narración").selectOption("es");
    await p.getByRole("radio", { name: "30s", exact: true }).click();
    await p.getByTestId("production-checklist").waitFor({ state: "visible", timeout: 30000 });
    return { state: "PASS", detail: "Tema, narración española y 30 s configurados; todavía sin generación." };
  });
  if (opened.state !== "PASS") return;
  if (!c.real) {
    await c.step("Modo gratuito: detener antes de crear o generar", async () => ({ state: "BLOCKED", detail: "Runner preparado; no se creó proyecto ni se contactó proveedor." })); return;
  }
  const created = await c.step("Crear solicitud y verificar su presupuesto persistido", async () => {
    // Creating only stores intent. No script, voice or image is generated by this Server Action.
    await p.getByRole("button", { name: "Crear solicitud", exact: true }).click();
    await p.waitForURL((u: URL) => u.pathname === "/dashboard" && u.searchParams.get("created") === "1", { timeout: 30000 });
    const link = p.getByRole("link", { name: title, exact: true });
    const href = await link.getAttribute("href");
    id = /^\/dashboard\/videos\/([0-9a-f-]{36})$/.exec(href ?? "")?.[1] ?? "";
    if (!id || !c.readReelCap) return { state: "BLOCKED", detail: "No hay identidad o lector de presupuesto verificable; no se genera." };
    const cap = await c.readReelCap(id);
    if (cap === null || !Number.isFinite(cap) || cap <= 0 || cap > 1.5) return { state: "BLOCKED", detail: "El techo persistido del Reel no cabe en USD 1.50; no se genera." };
    const state = await c.ledger?.state().catch(() => null) ?? null;
    const guard = campaign320SpendGate("reels", { real: c.real, killSwitch: c.killSwitch?.() === true, stopped: !c.ledger?.stopped || await c.ledger.stopped().catch(() => true), ledger: state, amountUsd: cap, runCapUsd: c.runCapUsd ?? 0, runCommittedUsd: 0 });
    if (!guard.ok || !c.ledger) return { state: "BLOCKED", detail: guard.reason };
    const r = await c.ledger.reserve({ key, module: "reels", jobId: c.jobId, reservedUsd: cap, at: new Date().toISOString() });
    reserved = r.ok;
    return { state: r.ok ? "PASS" : "BLOCKED", detail: r.ok ? `Tope íntegro persistido y reservado: USD ${cap.toFixed(2)}.` : r.reason };
  });
  if (created.state !== "PASS" || !reserved) return;
  const allowed = async () => c.killSwitch?.() === true && !!c.ledger?.stopped && !await c.ledger.stopped().catch(() => true);
  const script = await c.step("Generar y revisar guion del Reel", async () => {
    if (!await allowed()) return { state: "BLOCKED", detail: "STOP o interruptor: se conserva reserva sin generar." };
    const card = p.getByRole("link", { name: title, exact: true }).locator('xpath=ancestor::div[.//button[normalize-space(.)="Generar guion"]][1]');
    await card.getByRole("button", { name: "Generar guion", exact: true }).click();
    await p.waitForURL(new RegExp(`/dashboard/review/${id}$`), { timeout: 120000 });
    return { state: "PASS", detail: "Guion generado y pantalla de revisión alcanzada." };
  });
  if (script.state !== "PASS") return;
  const render = await c.step("Generar MP4 del Reel una sola vez", async () => {
    if (!await allowed()) return { state: "BLOCKED", detail: "STOP o interruptor antes del render." };
    await p.getByRole("button", { name: "Generar video final", exact: true }).click();
    await p.waitForURL(new RegExp(`/dashboard/videos/${id}`), { timeout: 30000 });
    return { state: "PASS", detail: "Render solicitado; sin reintentos automáticos." };
  });
  if (render.state !== "PASS") return;
  const samples: { t: number; progress: string | null }[] = [], start = Date.now();
  const complete = await c.step("Observar progreso, reproducción y descarga", async () => {
    while (Date.now() - start < 30 * 60000) {
      if (await p.getByRole("link", { name: "Descargar video", exact: true }).isVisible().catch(() => false)) break;
      if (/No se pudo generar|Producción cancelada/.test(await p.locator("body").innerText())) return { state: "FAIL", detail: "La producción falló; no se reintenta ni liquida una estimación como gasto real." };
      samples.push({ t: Date.now() - start, progress: await p.getByRole("progressbar").getAttribute("aria-valuenow").catch(() => null) });
      await sleep(10000); await p.reload({ waitUntil: "domcontentloaded" });
    }
    await writeFile(path.join(c.out, "reel-progress.json"), JSON.stringify(samples));
    const video = p.locator("video").first();
    const played = await video.evaluate(async (v: HTMLVideoElement) => { v.muted = true; await v.play(); await new Promise(r => setTimeout(r, 1500)); return v.currentTime > 0 && !v.error; }).catch(() => false);
    const [dl] = await Promise.all([p.waitForEvent("download", { timeout: 30000 }), p.getByRole("link", { name: "Descargar video", exact: true }).click()]);
    const file = path.join(c.out, "reel-30s.mp4"); await dl.saveAs(file);
    const facts = await measureVideo(file, { ffprobe: c.ffprobe, ffmpeg: c.ffmpeg });
    c.media.push(await c.probe(file, 30, null));
    await writeFile(path.join(c.out, "reel-measured.json"), JSON.stringify({ ...facts, played, subtitles: "NOT_MEASURED", billedCost: "NOT_RECONCILED_RESERVATION_REMAINS_OPEN" }, null, 2));
    const valid = played && facts.decodeOk && !!facts.audio && facts.video?.width === 1080 && facts.video?.height === 1920 && facts.durationSeconds !== null && Math.abs(facts.durationSeconds - 30) <= 2;
    return { state: valid ? "PASS" : "FAIL", detail: valid ? "MP4 descargado, decodificado y reproducible; subtítulos y gasto requieren acreditación separada." : "MP4 no cumple las medidas requeridas." };
  });
  // A complete commercial PASS additionally requires real subtitle and billing evidence.
  c.setHumanGate(complete.state === "PASS" ? "MP4 disponible: faltan medición de subtítulos y conciliación de gasto real; reserva abierta, no repetir." : "Reel incompleto: conservar reserva hasta conciliar gasto real; no repetir a ciegas.");
}
